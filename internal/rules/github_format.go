package rules

import (
	"bytes"
	"fmt"
	"os"
	"strings"
)

// FormatGitHubAnnotations converts findings into GitHub Actions workflow command annotations.
func FormatGitHubAnnotations(findings []Finding) string {
	var buf bytes.Buffer
	for _, f := range findings {
		cmdType := "warning"
		if f.Severity == SeverityError {
			cmdType = "error"
		} else if f.Severity == SeverityInfo {
			cmdType = "notice"
		}

		// Escape newlines for GitHub workflow command syntax
		escapedMsg := strings.ReplaceAll(f.Message, "%", "%25")
		escapedMsg = strings.ReplaceAll(escapedMsg, "\r", "%0D")
		escapedMsg = strings.ReplaceAll(escapedMsg, "\n", "%0A")

		line := f.Line
		if line < 1 {
			line = 1
		}
		col := f.Column
		if col < 1 {
			col = 1
		}

		buf.WriteString(fmt.Sprintf("::%s file=%s,line=%d,col=%d,title=[%s]::%s\n",
			cmdType, f.Path, line, col, f.Rule, escapedMsg))
	}
	return buf.String()
}

// FormatStepSummary creates a GitHub Actions Job Summary Markdown report.
func FormatStepSummary(findings []Finding, filesCount int) string {
	var buf bytes.Buffer

	buf.WriteString("## 🛡️ gha-local-lint Analysis Report\n\n")

	errCount := 0
	warnCount := 0
	for _, f := range findings {
		if f.Severity == SeverityError {
			errCount++
		} else if f.Severity == SeverityWarning {
			warnCount++
		}
	}

	if len(findings) == 0 {
		buf.WriteString(fmt.Sprintf("✅ **Passed**: Verified `%d` workflow file(s) with **0 issues found**.\n\n", filesCount))
		buf.WriteString("| Check | Status |\n")
		buf.WriteString("| :--- | :--- |\n")
		buf.WriteString("| Job DAG Cycles & Missing Needs | ✅ Passed |\n")
		buf.WriteString("| Output Reference Integrity | ✅ Passed |\n")
		buf.WriteString("| Script Injection Vulnerabilities | ✅ Clean |\n")
		buf.WriteString("| 40-character Action SHA Pinning | ✅ Verified |\n")
		buf.WriteString("| Permissions Least-Privilege | ✅ Compliant |\n")
		return buf.String()
	}

	buf.WriteString(fmt.Sprintf("⚠️ **Status**: Found `%d` issue(s) across `%d` file(s) (`%d` errors, `%d` warnings).\n\n",
		len(findings), filesCount, errCount, warnCount))

	buf.WriteString("| Severity | File | Line:Col | Rule | Message |\n")
	buf.WriteString("| :--- | :--- | :--- | :--- | :--- |\n")

	for _, f := range findings {
		sevBadge := "🟡 Warning"
		if f.Severity == SeverityError {
			sevBadge = "🔴 Error"
		} else if f.Severity == SeverityInfo {
			sevBadge = "ℹ️ Info"
		}

		cleanMsg := strings.ReplaceAll(f.Message, "|", "\\|")
		buf.WriteString(fmt.Sprintf("| %s | `%s` | `%d:%d` | `%s` | %s |\n",
			sevBadge, f.Path, f.Line, f.Column, f.Rule, cleanMsg))
	}

	buf.WriteString("\n---\n*Report generated by [gha-local-lint](https://github.com/smford/gha-local-lint)*\n")
	return buf.String()
}

// WriteStepSummary writes the step summary markdown to $GITHUB_STEP_SUMMARY if configured.
func WriteStepSummary(summary string) error {
	summaryPath := os.Getenv("GITHUB_STEP_SUMMARY")
	if summaryPath == "" {
		return nil
	}
	f, err := os.OpenFile(summaryPath, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0644)
	if err != nil {
		return err
	}
	defer f.Close()
	_, err = f.WriteString(summary)
	return err
}
